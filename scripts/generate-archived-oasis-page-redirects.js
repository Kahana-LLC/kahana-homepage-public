/**
 * Generate redirects for archived Oasis marketing pages (not pricing/installations).
 * Run: node scripts/generate-archived-oasis-page-redirects.js
 */
const fs = require('fs');
const path = require('path');

const ARCHIVE_PAGES = path.join(__dirname, '../archive/pages');

/** @type {{ source: string, destination: string, permanent: boolean }[]} */
const redirects = [];

function add(source, destination) {
  redirects.push({ source, destination, permanent: true });
}

// Root-level archived pages
for (const file of fs.readdirSync(ARCHIVE_PAGES).filter((f) => f.endsWith('.jsx'))) {
  const base = file.replace(/\.jsx$/, '');
  // Prefer pricing for install-related leftovers; otherwise home
  const dest =
    base.includes('beta') || base.includes('waitlist') || base.includes('mobile')
      ? '/oasis-pricing'
      : '/';
  add(`/${base}`, dest);
}

// Features → /help (Features surface retired)
const featuresDir = path.join(ARCHIVE_PAGES, 'features');
if (fs.existsSync(featuresDir)) {
  for (const file of fs.readdirSync(featuresDir).filter((f) => f.endsWith('.jsx'))) {
    add(`/features/${file.replace(/\.jsx$/, '')}`, '/help');
  }
}

// Products → /oasis-pricing (pay/install)
const productsDir = path.join(ARCHIVE_PAGES, 'products');
if (fs.existsSync(productsDir)) {
  add('/products', '/oasis-pricing');
  for (const file of fs.readdirSync(productsDir).filter((f) => f.endsWith('.jsx') && f !== 'index.jsx')) {
    add(`/products/${file.replace(/\.jsx$/, '')}`, '/oasis-pricing');
  }
}

// Markets → /
const marketsDir = path.join(ARCHIVE_PAGES, 'markets');
if (fs.existsSync(marketsDir)) {
  add('/markets', '/');
  for (const file of fs.readdirSync(marketsDir).filter((f) => f.endsWith('.jsx') && f !== 'index.jsx')) {
    add(`/markets/${file.replace(/\.jsx$/, '')}`, '/');
  }
}

// Solutions → /
const solutionsDir = path.join(ARCHIVE_PAGES, 'solutions');
if (fs.existsSync(solutionsDir)) {
  add('/solutions', '/');
  for (const file of fs.readdirSync(solutionsDir).filter((f) => f.endsWith('.jsx') && f !== 'index.jsx')) {
    add(`/solutions/${file.replace(/\.jsx$/, '')}`, '/');
  }
}

// Use-cases: keep Oasis child pages redirected; /use-cases is a live Kahana page.
const useCasesDir = path.join(ARCHIVE_PAGES, 'use-cases');
if (fs.existsSync(useCasesDir)) {
  for (const file of fs.readdirSync(useCasesDir).filter((f) => f.endsWith('.jsx'))) {
    add(`/use-cases/${file.replace(/\.jsx$/, '')}`, '/');
  }
}

// Dedupe by source (last wins)
const bySource = new Map();
for (const r of redirects) bySource.set(r.source, r);
const pageRedirects = [...bySource.values()].sort((a, b) => a.source.localeCompare(b.source));

const outPath = path.join(__dirname, '../config/archivedOasisPageRedirects.js');
fs.writeFileSync(
  outPath,
  `/**
 * Auto-generated redirects for archived Oasis marketing pages.
 * Regenerated by: node scripts/generate-archived-oasis-page-redirects.js
 * Kept live: /oasis-pricing, /installations, /oasis-auth, surveys.
 */
module.exports = ${JSON.stringify({ pageRedirects }, null, 2)};
`
);

console.log(`Wrote ${outPath} (${pageRedirects.length} redirects)`);
