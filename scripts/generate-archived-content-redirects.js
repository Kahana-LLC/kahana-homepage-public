/**
 * Generate next.config-compatible redirects for archived blog/docs JSON.
 * Run from repo root: node scripts/generate-archived-content-redirects.js
 */
const fs = require('fs');
const path = require('path');

function slugsFromDir(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => {
      try {
        const j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
        return j.slug || f.replace(/\.json$/, '');
      } catch {
        return f.replace(/\.json$/, '');
      }
    })
    .filter(Boolean)
    .sort();
}

const blog = slugsFromDir(path.join(__dirname, '../archive/data/blog'));
const docs = slugsFromDir(path.join(__dirname, '../archive/data/docs'));

const blogRedirects = blog.map((slug) => ({
  source: `/blog/${slug}`,
  destination: '/blog',
  permanent: true,
}));

const docsRedirects = docs.map((slug) => ({
  source: `/docs/${slug}`,
  destination: '/help',
  permanent: true,
}));

const outPath = path.join(__dirname, '../config/archivedContentRedirects.js');
const body = `/**
 * Auto-generated redirects for archived Oasis-era blog/docs.
 * Regenerated by: node scripts/generate-archived-content-redirects.js
 * Do not hand-edit.
 */
module.exports = ${JSON.stringify({ blogRedirects, docsRedirects }, null, 2)};
`;

fs.writeFileSync(outPath, body);
console.log(`Wrote ${outPath}`);
console.log(`blog redirects: ${blogRedirects.length}, docs redirects: ${docsRedirects.length}`);
